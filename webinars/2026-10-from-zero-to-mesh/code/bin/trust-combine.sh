#!/usr/bin/env bash
# Copy every zone's CA certificate into the other zones as MeshTrust resources.
# Each zone makes its own CA, so cross-zone calls fail until every zone trusts the other CAs.
# Usage: trust-combine.sh
#   MESH_NAME       mesh whose MeshTrusts are copied
#   ZONE_CONTEXTS   kubectl contexts of the zones, separated by spaces or commas (two or more, no duplicates)
#   COMBINED        optional. Set to 1 to apply one combined MeshTrust (all CAs, one trust domain)
#                   to every zone instead. A MeshTrust names one trust domain, so this mode needs
#                   every zone to report the same one. The script refuses when they differ.
# Default mode follows the Kong docs example: one MeshTrust per source zone, named <zone>-trust,
# with that zone's own trust domain and CA, applied to every other zone. The labels are
# kuma.io/origin: zone, kuma.io/mesh and kuma.io/zone (the zone it is applied to).
# The script reads only MeshTrust objects. It checks every block before it applies anything:
# each zone must give exactly one block, the block must be a parseable CERTIFICATE, and no
# block or surrounding text may mention a private key. It prints no certificate text.
# The certificates are public. In combined mode jq --argjson puts their PEM text in argv.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
. "$here/../lib/common.sh"

NS=kong-mesh-system
COMBINED_NAME=webinar-combined-trust

require_vars MESH_NAME ZONE_CONTEXTS
[[ $MESH_NAME =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]] || { _err "MESH_NAME must be lowercase letters, digits and hyphens"; exit 2; }
[ -z "${TRUST_DOMAIN:-}" ] || { _err "TRUST_DOMAIN is not supported: a CA filed under a trust domain it does not hold fails validation. Use COMBINED=1 only when every zone shares one trust domain"; exit 2; }
case "${COMBINED:-}" in "" | 0 | 1) ;; *) _err "COMBINED must be 1 or unset"; exit 2 ;; esac
combined=0
[ "${COMBINED:-}" = "1" ] && combined=1
read -r -a contexts <<<"${ZONE_CONTEXTS//,/ }"
[ "${#contexts[@]}" -ge 2 ] || { _err "ZONE_CONTEXTS needs at least two contexts"; exit 2; }
for c in "${contexts[@]}"; do
  [[ $c =~ ^[A-Za-z0-9._:/@-]+$ ]] || { _err "unexpected characters in context name"; exit 2; }
  [[ $c != *..* ]] || { _err "context name must not contain .."; exit 2; }
done
dups="$(printf '%s\n' "${contexts[@]}" | sort | uniq -d)"
[ -z "$dups" ] || { _err "ZONE_CONTEXTS lists a context twice"; exit 2; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# split_blocks <pem-file> <out-dir>: one file per BEGIN..END block. Fails on text outside a block.
split_blocks() {
  mkdir -p "$2"
  awk -v dir="$2" '
    /^-----BEGIN / { inblock = 1; n++; f = sprintf("%s/block-%03d.pem", dir, n) }
    inblock { print > f }
    !inblock && $0 !~ /^[[:space:]]*$/ { stray = 1 }
    /^-----END / { inblock = 0 }
    END { if (inblock || stray) exit 3 }
  ' "$1"
}

# Work directories are named by position (z0, z1, ...), never by context name.
n="${#contexts[@]}"
for ((i = 0; i < n; i++)); do
  c="${contexts[$i]}"
  zdir="$tmp/z$i"
  mkdir -p "$zdir"
  kubectl --context "$c" get meshtrust -n "$NS" -o json >"$zdir/list.json"
  # Autogenerated MeshTrusts of this mesh (they carry an origin). Our own copies are skipped.
  jq --arg mesh "$MESH_NAME" --arg combined "$COMBINED_NAME" \
    '[.items[]
      | select(.metadata.name != $combined)
      | select(.metadata.labels["kuma.io/mesh"] == $mesh)
      | select(.spec.origin != null or .status.origin != null)]' "$zdir/list.json" >"$zdir/own.json"
  [ "$(jq 'length' "$zdir/own.json")" -eq 1 ] || { _err "$c: expected exactly one generated MeshTrust for mesh $MESH_NAME"; exit 1; }
  jq -r '.[0].spec.trustDomain // empty' "$zdir/own.json" >"$zdir/domain"
  domain="$(cat "$zdir/domain")"
  { [ -n "$domain" ] && [[ $domain =~ ^[A-Za-z0-9]([A-Za-z0-9._-]*[A-Za-z0-9])?$ ]]; } || { _err "$c: the generated MeshTrust has no usable trustDomain"; exit 1; }
  jq -r '.[0].metadata.labels["kuma.io/zone"] // empty' "$zdir/own.json" >"$zdir/zone"
  zname="$(cat "$zdir/zone")"
  [[ $zname =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ ]] || { _err "$c: the generated MeshTrust has no usable kuma.io/zone label"; exit 1; }
  jq -r '.[0].spec.caBundles[] | select(.type == "Pem") | .pem.value' "$zdir/own.json" >"$zdir/bundle.pem"

  if grep -qi 'PRIVATE KEY' "$zdir/bundle.pem"; then
    _err "$c: the bundle mentions a private key, nothing applied"
    exit 1
  fi
  split_blocks "$zdir/bundle.pem" "$zdir/blocks" || { _err "$c: text outside a PEM block or an unclosed block"; exit 1; }
  nblocks="$(find "$zdir/blocks" -name 'block-*.pem' 2>/dev/null | wc -l | tr -d ' ')"
  [ "$nblocks" -eq 1 ] || { _err "$c: expected one CA certificate, found $nblocks"; exit 1; }
  blk="$zdir/blocks/block-001.pem"
  [ "$(head -n 1 "$blk")" = "-----BEGIN CERTIFICATE-----" ] || { _err "$c: the block is not a CERTIFICATE"; exit 1; }
  [ "$(tail -n 1 "$blk")" = "-----END CERTIFICATE-----" ] || { _err "$c: the block is not a CERTIFICATE"; exit 1; }
  openssl x509 -noout <"$blk" >/dev/null 2>&1 || { _err "$c: the certificate does not parse"; exit 1; }
done

# Zone names must differ, or two MeshTrusts would share a name.
[ "$(cat "$tmp"/z*/zone | sort -u | wc -l | tr -d ' ')" -eq "$n" ] || { _err "two contexts report the same zone name"; exit 1; }

# Build every resource first, then apply. A failure above or here applies nothing.
mkdir -p "$tmp/out"
if [ "$combined" -eq 1 ]; then
  [ "$(cat "$tmp"/z*/domain | sort -u | wc -l | tr -d ' ')" -eq 1 ] || {
    _err "COMBINED=1 needs one shared trust domain and the zones report different ones. Leave COMBINED unset for one MeshTrust per zone"
    exit 1
  }
  domain="$(head -n 1 "$tmp/z0/domain")"
  bundles='[]'
  for ((i = 0; i < n; i++)); do
    bundles="$(jq --rawfile pem "$tmp/z$i/blocks/block-001.pem" '. + [{type: "Pem", pem: {value: $pem}}]' <<<"$bundles")"
  done
  jq -n --arg ns "$NS" --arg name "$COMBINED_NAME" --arg mesh "$MESH_NAME" --arg td "$domain" --argjson bundles "$bundles" \
    '{apiVersion: "kuma.io/v1alpha1", kind: "MeshTrust",
      metadata: {name: $name, namespace: $ns, labels: {"kuma.io/mesh": $mesh, "kuma.io/origin": "zone"}},
      spec: {trustDomain: $td, caBundles: $bundles}}' >"$tmp/out/combined.json"
else
  for ((i = 0; i < n; i++)); do
    for ((j = 0; j < n; j++)); do
      [ "$i" -ne "$j" ] || continue
      jq -n --arg ns "$NS" --arg mesh "$MESH_NAME" --arg src "$(cat "$tmp/z$i/zone")" --arg dst "$(cat "$tmp/z$j/zone")" \
        --arg td "$(cat "$tmp/z$i/domain")" --rawfile pem "$tmp/z$i/blocks/block-001.pem" \
        '{apiVersion: "kuma.io/v1alpha1", kind: "MeshTrust",
          metadata: {name: ($src + "-trust"), namespace: $ns,
                     labels: {"kuma.io/mesh": $mesh, "kuma.io/origin": "zone", "kuma.io/zone": $dst}},
          spec: {trustDomain: $td, caBundles: [{type: "Pem", pem: {value: $pem}}]}}' >"$tmp/out/from-$i-to-$j.json"
    done
  done
fi

for ((j = 0; j < n; j++)); do
  c="${contexts[$j]}"
  if [ "$combined" -eq 1 ]; then
    kubectl --context "$c" apply -f - <"$tmp/out/combined.json" >/dev/null
    echo "combined MeshTrust ($COMBINED_NAME, $n CA certificates) applied to $c"
  else
    for ((i = 0; i < n; i++)); do
      [ "$i" -ne "$j" ] || continue
      kubectl --context "$c" apply -f - <"$tmp/out/from-$i-to-$j.json" >/dev/null
    done
    echo "$((n - 1)) per-zone MeshTrusts applied to $c"
  fi
done
